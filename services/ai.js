export async function analyzeProject(project) {
    if (!groq) {
        throw new Error('GROQ_API_KEY не найден в .env');
    }

    const now = Date.now();
    const available = MODELS.filter((model) => (cooldownUntil.get(model) ?? 0) <= now);

    if (available.length === 0) {
        const waitSec = Math.ceil((Math.min(...cooldownUntil.values()) - now) / 1000);
        throw new Error(`Лимит Groq исчерпан для всех моделей, повтор через ~${waitSec} с`);
    }

    let lastError;

    for (const model of available) {
        try {
            const result = await requestAnalysis(model, project);
            cooldownUntil.delete(model);
            return result;
        } catch (error) {
            if (error?.status !== 429) {
                throw error;
            }

            cooldownUntil.set(model, Date.now() + parseRetryDelayMs(error));
            lastError = error;
        }
    }

    throw lastError;
}

async function requestAnalysis(model, project) {
    const response = await groq.chat.completions.create({
        model,
        temperature: 0.4,
        messages: [
            {
                role: 'system',
                content: SYSTEM_PROMPT,
            },
            {
                role: 'user',
                content: JSON.stringify({
                    title: project.title,
                    description: project.description,
                    budget: project.budget,
                    category: project.category,
                    url: project.url,
                }),
            },
        ],
        response_format: { type: 'json_object' },
    });

    const content = response.choices[0]?.message?.content;

    if (!content) {
        throw new Error('Groq вернул пустой ответ');
    }

    const result = JSON.parse(content);

    if (
        typeof result.isRelevant !== 'boolean' ||
        !Number.isFinite(result.score) ||
        !['high', 'medium', 'low'].includes(result.priority) ||
        typeof result.reason !== 'string' ||
        typeof result.draftReply !== 'string' ||
        typeof result.suggestedBudget !== 'string' ||
        !Number.isInteger(result.estimatedDays) ||
        result.estimatedDays < 0
    ) {
        throw new Error('Groq вернул JSON с неправильной структурой');
    }

    result.score = Math.max(0, Math.min(100, result.score));

    return result;
}
